//! Emits target-specific Vulkan platform dispatch modules.
//!
//! The translated Vulkan platform headers remain the ABI authority. This
//! emitter adds only the platform proc tables and adapters needed to cross from
//! the core Vulkan module to those official translated declarations.
const std = @import("std");

pub const LinuxOptions = struct {
    /// Emit Wayland fields only when the Linux ABI translation includes Wayland.
    wayland: bool = false,
};

pub const Target = union(enum) {
    linux: LinuxOptions,
    android,
};

/// Write one complete platform dispatch module. Linux always emits Xlib and
/// emits Wayland only when the translated platform module contains its types.
pub fn render(writer: *std.Io.Writer, target: Target) std.Io.Writer.Error!void {
    switch (target) {
        .linux => |options| try emitLinux(writer, options),
        .android => try emitAndroid(writer),
    }
}

fn emitLinux(writer: *std.Io.Writer, options: LinuxOptions) std.Io.Writer.Error!void {
    try writer.writeAll(
        \\//! Platform-specific Vulkan dispatch. Generated by `tools/gen_platform_dispatch.zig`.
        \\const core = @import("vulkan");
        \\const core_dispatch = @import("dispatch.zig");
        \\const platform = @import("vulkan_platform");
        \\
        \\pub const InstanceProcs = struct {
        \\    create_xlib_surface_khr: platform.PFN_vkCreateXlibSurfaceKHR = null,
        \\    get_physical_device_xlib_presentation_support_khr: platform.PFN_vkGetPhysicalDeviceXlibPresentationSupportKHR = null,
        \\
    );
    if (options.wayland) {
        try writer.writeAll(
            \\    create_wayland_surface_khr: platform.PFN_vkCreateWaylandSurfaceKHR = null,
            \\    get_physical_device_wayland_presentation_support_khr: platform.PFN_vkGetPhysicalDeviceWaylandPresentationSupportKHR = null,
            \\
        );
    }
    try writer.writeAll(
        \\};
        \\
        \\pub fn loadInstanceProcs(
        \\    get_instance_proc_addr: core.PFN_vkGetInstanceProcAddr,
        \\    instance: core.VkInstance,
        \\    enabled_extensions: core_dispatch.EnabledInstanceExts,
        \\) core_dispatch.LoadError!InstanceProcs {
        \\    const get_proc = get_instance_proc_addr orelse return error.MissingInstanceProc;
        \\    var procs: InstanceProcs = .{};
        \\
        \\    if (enabled_extensions.has(.xlib_surface)) {
        \\        const create = get_proc(instance, "vkCreateXlibSurfaceKHR") orelse
        \\            return error.MissingInstanceProc;
        \\        const present = get_proc(instance, "vkGetPhysicalDeviceXlibPresentationSupportKHR") orelse
        \\            return error.MissingInstanceProc;
        \\        procs.create_xlib_surface_khr = @ptrCast(create);
        \\        procs.get_physical_device_xlib_presentation_support_khr = @ptrCast(present);
        \\    }
        \\
    );

    if (options.wayland) {
        try writer.writeAll(
            \\    if (enabled_extensions.has(.wayland_surface)) {
            \\        const create = get_proc(instance, "vkCreateWaylandSurfaceKHR") orelse
            \\            return error.MissingInstanceProc;
            \\        const present = get_proc(instance, "vkGetPhysicalDeviceWaylandPresentationSupportKHR") orelse
            \\            return error.MissingInstanceProc;
            \\        procs.create_wayland_surface_khr = @ptrCast(create);
            \\        procs.get_physical_device_wayland_presentation_support_khr = @ptrCast(present);
            \\    }
            \\
        );
    }

    try writer.writeAll(
        \\    return procs;
        \\}
        \\
        \\pub fn createXlibSurface(
        \\    self: *const InstanceProcs,
        \\    instance: core.VkInstance,
        \\    info: *const platform.VkXlibSurfaceCreateInfoKHR,
        \\    surface: *core.VkSurfaceKHR,
        \\) core_dispatch.LoadError!core.VkResult {
        \\    const create = self.create_xlib_surface_khr orelse return error.MissingInstanceProc;
        \\    const result = create(@ptrCast(instance), info, null, @ptrCast(surface));
        \\    return result;
        \\}
        \\
    );

    if (options.wayland) {
        try writer.writeAll(
            \\pub fn createWaylandSurface(
            \\    self: *const InstanceProcs,
            \\    instance: core.VkInstance,
            \\    info: *const platform.VkWaylandSurfaceCreateInfoKHR,
            \\    surface: *core.VkSurfaceKHR,
            \\) core_dispatch.LoadError!core.VkResult {
            \\    const create = self.create_wayland_surface_khr orelse return error.MissingInstanceProc;
            \\    const result = create(@ptrCast(instance), info, null, @ptrCast(surface));
            \\    return result;
            \\}
            \\
        );
    }
    try writer.writeAll(
        \\pub const DeviceProcs = struct {};
        \\
        \\pub fn loadDeviceProcs(
        \\    _: core.PFN_vkGetDeviceProcAddr,
        \\    _: core.VkDevice,
        \\    _: core_dispatch.EnabledDeviceExts,
        \\) core_dispatch.LoadError!DeviceProcs {
        \\    return .{};
        \\}
        \\
    );
}

fn emitAndroid(writer: *std.Io.Writer) std.Io.Writer.Error!void {
    try writer.writeAll(
        \\//! Platform-specific Vulkan dispatch. Generated by `tools/gen_platform_dispatch.zig`.
        \\const core = @import("vulkan");
        \\const core_dispatch = @import("dispatch.zig");
        \\const platform = @import("vulkan_platform");
        \\const android_platform = @import("android_platform");
        \\
        \\pub const InstanceProcs = struct {
        \\    create_android_surface_khr: platform.PFN_vkCreateAndroidSurfaceKHR = null,
        \\};
        \\
        \\pub fn loadInstanceProcs(
        \\    get_instance_proc_addr: core.PFN_vkGetInstanceProcAddr,
        \\    instance: core.VkInstance,
        \\    enabled_extensions: core_dispatch.EnabledInstanceExts,
        \\) core_dispatch.LoadError!InstanceProcs {
        \\    const get_proc = get_instance_proc_addr orelse return error.MissingInstanceProc;
        \\    var procs: InstanceProcs = .{};
        \\    if (enabled_extensions.has(.android_surface)) {
        \\        const create = get_proc(instance, "vkCreateAndroidSurfaceKHR") orelse
        \\            return error.MissingInstanceProc;
        \\        procs.create_android_surface_khr = @ptrCast(create);
        \\    }
        \\    return procs;
        \\}
        \\
        \\pub fn createAndroidSurface(
        \\    self: *const InstanceProcs,
        \\    instance: core.VkInstance,
        \\    info: *const platform.VkAndroidSurfaceCreateInfoKHR,
        \\    surface: *core.VkSurfaceKHR,
        \\) core_dispatch.LoadError!core.VkResult {
        \\    const create = self.create_android_surface_khr orelse return error.MissingInstanceProc;
        \\    const result = create(@ptrCast(instance), info, null, @ptrCast(surface));
        \\    return result;
        \\}
        \\
        \\pub const DeviceProcs = struct {
        \\    get_android_hardware_buffer_properties: platform.PFN_vkGetAndroidHardwareBufferPropertiesANDROID = null,
        \\};
        \\
        \\pub fn loadDeviceProcs(
        \\    get_device_proc_addr: core.PFN_vkGetDeviceProcAddr,
        \\    device: core.VkDevice,
        \\    enabled_extensions: core_dispatch.EnabledDeviceExts,
        \\) core_dispatch.LoadError!DeviceProcs {
        \\    const get_proc = get_device_proc_addr orelse return error.MissingDeviceProc;
        \\    var procs: DeviceProcs = .{};
        \\    if (enabled_extensions.has(.external_memory_android_hardware_buffer)) {
        \\        const properties = get_proc(device, "vkGetAndroidHardwareBufferPropertiesANDROID") orelse
        \\            return error.MissingDeviceProc;
        \\        procs.get_android_hardware_buffer_properties = @ptrCast(properties);
        \\    }
        \\    return procs;
        \\}
        \\
        \\pub fn getAndroidHardwareBufferProperties(
        \\    self: *const DeviceProcs,
        \\    device: core.VkDevice,
        \\    buffer: ?*android_platform.AHardwareBuffer,
        \\    properties: *platform.VkAndroidHardwareBufferPropertiesANDROID,
        \\) core_dispatch.LoadError!core.VkResult {
        \\    const get_properties = self.get_android_hardware_buffer_properties orelse
        \\        return error.MissingDeviceProc;
        \\    const result = get_properties(@ptrCast(device), ahbForVulkan(buffer), properties);
        \\    return result;
        \\}
        \\
        \\pub fn ahbForVulkan(buffer: ?*android_platform.AHardwareBuffer) ?*platform.struct_AHardwareBuffer {
        \\    return if (buffer) |value| @ptrCast(value) else null;
        \\}
        \\
        \\pub fn imageForVulkan(image: core.VkImage) platform.VkImage {
        \\    return @ptrCast(image);
        \\}
        \\
    );
}
